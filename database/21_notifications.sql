-- ============================================================
-- 21_notifications.sql
-- Bulk Notification Center (admin portal) + member inbox (app).
--
-- WHY: two features depend on this one table:
--   1. the portal's Notifications page drafts AUTOMATED payment
--      reminders — every released loan's schedule is walked, and
--      the ones with a deadline inside the admin's chosen window
--      are listed for one-click bulk sending;
--   2. every decision on an app-filed loan request (approved /
--      returned / rejected) writes the member a notice, so the
--      member learns the outcome in the app instead of coming to
--      the office to ask. Returned/rejected notices carry the
--      admin's remarks verbatim.
--
-- Delivery today is IN-APP: the app reads its own rows under RLS
-- and marks them read. True OS push (FCM) is a v1.1 upgrade on
-- top of this same table — no schema change needed later.
--
-- Run AFTER: 20_loan_application_remarks.sql
-- Safe to re-run (IF NOT EXISTS / DROP IF EXISTS everywhere).
-- Existing rows are untouched — only this new table.
-- Hans runs this in the SQL Editor — no other setup required.
-- ============================================================


-- ---------- 1. Table ----------

CREATE TABLE IF NOT EXISTS notification (
  notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id       integer NOT NULL REFERENCES member(member_id) ON DELETE CASCADE,
  loan_id         integer REFERENCES loan(loan_id) ON DELETE SET NULL,
  -- payment_due | payment_overdue | loan_approved | loan_returned | loan_rejected
  type            varchar(30) NOT NULL,
  title           varchar(120) NOT NULL,
  body            text NOT NULL,
  -- null = written by the system (bulk reminders still record the admin)
  created_by      integer REFERENCES admin(admin_id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  read_at         timestamptz
);

CREATE INDEX IF NOT EXISTS notification_member_idx ON notification (member_id, created_at DESC);
CREATE INDEX IF NOT EXISTS notification_loan_idx   ON notification (loan_id);


-- ---------- 2. Row-level security ----------

ALTER TABLE notification ENABLE ROW LEVEL SECURITY;

-- Admins: full access — the portal drafts, sends and audits here.
DROP POLICY IF EXISTS "admin manage notifications" ON notification;
CREATE POLICY "admin manage notifications" ON notification FOR ALL
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- Members: read their own inbox (RLS has no column filter, so the
-- app's SELECT only ever returns rows for its own member_id)...
DROP POLICY IF EXISTS "member read own notifications" ON notification;
CREATE POLICY "member read own notifications" ON notification FOR SELECT
  TO authenticated
  USING (member_id IN (SELECT member_id FROM member WHERE auth_uid = auth.uid()));

-- ...and mark their own rows as read. There is deliberately NO
-- member INSERT and NO member DELETE: every message comes from the
-- portal, and messages are history (RA 9520 / AMLA — no lost trail).
DROP POLICY IF EXISTS "member mark own notifications read" ON notification;
CREATE POLICY "member mark own notifications read" ON notification FOR UPDATE
  TO authenticated
  USING (member_id IN (SELECT member_id FROM member WHERE auth_uid = auth.uid()))
  WITH CHECK (member_id IN (SELECT member_id FROM member WHERE auth_uid = auth.uid()));


-- ---------- 3. Content freeze ----------
-- RLS policies cannot restrict WHICH columns a row updates, so this
-- trigger does: a member may only move read_at. Title, body and
-- target belong to the portal forever.

CREATE OR REPLACE FUNCTION notification_freeze() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.member_id   IS DISTINCT FROM OLD.member_id
     OR NEW.loan_id  IS DISTINCT FROM OLD.loan_id
     OR NEW.type     IS DISTINCT FROM OLD.type
     OR NEW.title    IS DISTINCT FROM OLD.title
     OR NEW.body     IS DISTINCT FROM OLD.body
     OR NEW.created_by IS DISTINCT FROM OLD.created_by
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'notification content is read-only — only read_at may change';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS notification_freeze ON notification;
CREATE TRIGGER notification_freeze
  BEFORE UPDATE ON notification
  FOR EACH ROW EXECUTE FUNCTION notification_freeze();


-- ---------- 4. Verify ----------
-- a) table — expect 10 columns, 2 indexes:
SELECT column_name, data_type, is_nullable
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'notification'
ORDER BY ordinal_position;

SELECT indexname FROM pg_indexes
WHERE schemaname = 'public' AND tablename = 'notification';

-- b) policies — expect 3 rows (admin ALL, member SELECT, member UPDATE):
SELECT policyname, cmd FROM pg_policies
WHERE schemaname = 'public' AND tablename = 'notification';

-- c) trigger — expect 1 row:
SELECT tgname FROM pg_trigger
WHERE tgrelid = 'public.notification'::regclass AND NOT tgisinternal;
